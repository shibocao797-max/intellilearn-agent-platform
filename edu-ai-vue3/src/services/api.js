  videoStatus: (videoId, params) => request(`/edu/resource/video/${encodeURIComponent(videoId)}/status`, { params }),
  quizList: params => request('/edu/quiz/user/list', { params }),
  quizDetail: id => request(`/edu/quiz/detail/${id}`),
  submitQuiz: data => request('/edu/quiz/submit', { method: 'POST', data }),
  quizRecords: params => request('/edu/quiz/records', { params }),
  quizStats: () => request('/edu/quiz/stats'),
  aiExplain: data => request('/edu/quiz/ai-explain', { method: 'POST', data }),
  quizQuestions: params => request('/edu/quiz/questions', { params }),
  quizQuestionFacets: () => request('/edu/quiz/question-facets'),
  wrongQuizQuestions: params => request('/edu/quiz/wrong-questions', { params }),
  activeQuizSession: () => request('/edu/quiz/sessions/active'),
