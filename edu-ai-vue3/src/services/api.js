  quizSessionResult: sessionId => request(`/edu/quiz/sessions/${encodeURIComponent(sessionId)}/result`),
  reportSummary: params => request('/edu/report/summary', { params }),
  reportDetailed: params => request('/edu/report/detailed', { params }),
  workspace: () => request('/edu/workspace'),
  saveWorkspace: data => request('/edu/workspace', { method: 'PUT', data })
