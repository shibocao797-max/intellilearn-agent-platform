  regenerateActionPlan: planId => request(`/edu/action-plans/${encodeURIComponent(planId)}/regenerate`, { method: 'POST' }),
  updateActionPlanItem: (itemId, status) => request(`/edu/action-plans/items/${encodeURIComponent(itemId)}`, { method: 'PATCH', data: { status } }),
  resources: params => request('/edu/resource/user/list', { params }),
  resourceDetail: id => request(`/edu/resource/detail/${id}`),
  deleteResource: id => request(`/edu/resource/user/${encodeURIComponent(id)}`, { method: 'DELETE' }),
