  uploadChatAttachment: (data, options = {}) => request('/edu/ai/attachments', { method: 'POST', data, ...options }),
  deleteChatAttachment: attachmentId => request(`/edu/ai/attachments/${encodeURIComponent(attachmentId)}`, { method: 'DELETE' }),
  transcribeSpeech: (data, options = {}) => request('/edu/ai/speech/transcribe', { method: 'POST', data, ...options }),
  sessions: () => request('/edu/ai/sessions'),
  newSession: () => request('/edu/ai/session/new', { method: 'POST' }),
  deleteSession: sessionId => request(`/edu/ai/session/${encodeURIComponent(sessionId)}`, { method: 'DELETE' }),
  conversation: sessionId => request(`/edu/ai/conversation/${encodeURIComponent(sessionId)}`),
  profile: () => request('/edu/profile'),
  profileDetail: () => request('/edu/profile/detail'),
  confirmProfileDimension: (dimensionKey, data) => request(`/edu/profile/dimensions/${encodeURIComponent(dimensionKey)}/confirmation`, { method: 'PATCH', data }),
  profileActionPlan: () => request('/edu/profile/action-plan', { method: 'POST' }),
  actionPlans: () => request('/edu/action-plans'),
